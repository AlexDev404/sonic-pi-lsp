# frozen_string_literal: true

# Writes docs/lint-rules.md from the rules' own metadata:
#   ruby scripts/gen-lint-docs.rb > docs/lint-rules.md
$LOAD_PATH.unshift File.expand_path("../lint/lib", __dir__)
require "splint/ast"
require "splint/knowledge"
require "splint/rules"
require "splint/config"

cats = { correctness: "Correctness", suspicious: "Suspicious code", performance: "Performance",
         compat: "Compatibility", style: "Style" }
puts "# Lint rules"
puts
puts "Every rule `sonicpi lint` knows, with its default severity in the `recommended`"
puts "preset. Set them in `.splintrc` (see [the README](../README.md#linting)); this"
puts "page is generated by `scripts/gen-lint-docs.rb`."
puts
puts "| Rule | Default | Fixable | Checks |"
puts "| --- | --- | --- | --- |"
Splint::Rules.all.values.sort_by { |k| [cats.keys.index(k.category), k.id] }.each do |k|
  puts "| [`#{k.id}`](##{k.id}) | #{k.severity} | #{k.fixable? ? 'yes' : ''} | #{k.summary} |"
end
cats.each do |cat, title|
  rules = Splint::Rules.all.values.select { |k| k.category == cat }.sort_by(&:id)
  next if rules.empty?

  puts
  puts "## #{title}"
  rules.each do |k|
    puts
    puts "### #{k.id}"
    puts
    puts "#{k.summary.sub(/\A./, &:upcase)}."
    puts
    puts k.details unless k.details.empty?
    puts unless k.details.empty?
    puts "- Default: `#{k.severity}`#{k.fixable? ? ' (fixed by `sonicpi lint --fix`)' : ''}"
    unless k.options.empty?
      puts "- Options: #{k.options.map { |o, d| "`#{o}` (default `#{d.inspect}`)" }.join(', ')}"
    end
    example = k.options.empty? ? "#{k.id}: warning" : "#{k.id}: { severity: warning, #{k.options.map { |o, d| "#{o}: #{d.inspect}" }.join(', ')} }"
    puts "- In `.splintrc`: `#{example}`"
  end
end
